"""Extract the parameter documentation the wizard shows from ArduPilot's metadata.

Input: tests/util/apm_pdef.json - Rover's parameter metadata, generated by ArduPilot from the @DisplayName /
@Description / @Units lines in its source (download: https://autotest.ardupilot.org/Parameters/Rover/apm.pdef.json).
Output: rover_wizard/ui/param_docs.json - name -> display name, description, units, range, named values, bitmask
bits and the reboot/read-only flags, for every Rover parameter (the help texts and the parameter list). Run again after downloading newer metadata:
python tests/util/extract_param_docs.py (the tests check that param_docs.json is up to date).
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "apm_pdef.json"
PROJECT = HERE.parent.parent
TARGET = PROJECT / "rover_wizard" / "ui" / "param_docs.json"


def _number(text: str) -> float:
    """A metadata number ("4", "0.5") as int if whole, else float."""
    value = float(text)
    return int(value) if value.is_integer() else value


def extract() -> dict:
    """name -> the documentation the wizard shows for every Rover parameter: display name, description, units,
    range, named values, bitmask bits, and whether a change needs a reboot or the parameter is read-only."""
    metadata = json.loads(SOURCE.read_text(encoding="utf-8"))
    docs = {}
    for group in metadata.values():
        for name, info in group.items():
            # the file also holds non-parameter entries (e.g. a format version)
            if not isinstance(info, dict) or not info.get("Description"):
                continue
            entry = {"name": info.get("DisplayName", ""), "description": info["Description"].strip()}
            if info.get("Units"):
                entry["units"] = info["Units"]
            if info.get("Range"):
                entry["range"] = [_number(info["Range"]["low"]), _number(info["Range"]["high"])]
            if info.get("Values"):
                entry["values"] = info["Values"]
            if info.get("Bitmask"):
                entry["bitmask"] = info["Bitmask"]
            if str(info.get("RebootRequired", "")).lower() == "true":
                entry["reboot"] = True
            if str(info.get("ReadOnly", "")).lower() == "true":
                entry["readonly"] = True
            docs[name] = entry
    return dict(sorted(docs.items()))


if __name__ == "__main__":
    docs = extract()
    TARGET.write_text(json.dumps(docs, indent=0, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{len(docs)} parameters -> {TARGET.relative_to(PROJECT)} ({TARGET.stat().st_size // 1024} kB)")
